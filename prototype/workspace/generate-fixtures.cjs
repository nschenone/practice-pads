// Run with NODE_PATH pointing to an external installation of @tonaljs/tonal 4.10.0.
const { Scale, Note, Interval } = require('@tonaljs/tonal');
const parents = ['C','G','D','A','E','B','F#','Db','Ab','Eb','Bb','F','C#','G#','D#'];
const families = {major:'major', melodic:'melodic minor', harmonic:'harmonic minor'};
const fixtures = Object.fromEntries(Object.entries(families).map(([family, scale]) => [family, Object.fromEntries(parents.map(parent => {
  const notes = Scale.get(`${parent} ${scale}`).notes;
  if (notes.length !== 7) throw new Error(`Missing scale: ${parent} ${scale}`);
  const intervals = notes.map((root, degree) => notes.map((_, i) => {
    const iv = Interval.get(Note.distance(root, notes[(degree + i) % 7]));
    return `${iv.alt < 0 ? 'b'.repeat(-iv.alt) : '#'.repeat(iv.alt)}${iv.num}`;
  }));
  return [parent, {notes, chromas: notes.map(Note.chroma), intervals}];
}))]));
console.log(`// Generated by generate-fixtures.cjs using @tonaljs/tonal 4.10.0.\nconst fixtures = ${JSON.stringify(fixtures, null, 2)};`);
